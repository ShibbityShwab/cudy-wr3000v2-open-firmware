#!/usr/bin/env python3
"""Join the vendor-driver H2D send catalog with the firmware's H2D handler tables.

Usage:
    h2d_join_vendor.py FIRMWARE.bin [SR-MESSAGE-CATALOG.md] [--all]

Inputs are local-only; nothing vendor is committed:
  * FIRMWARE.bin - the Wi-Fi firmware image (928,920 B). Only ids/addresses
    are read; no firmware bytes are printed.
  * SR-MESSAGE-CATALOG.md - committed phase-37 catalog of vendor host builders
    that post HCC host->device messages
    (opensource/docs/phase37/sr-message-catalog.md).
"""
import sys, os, re, struct

BASE = 0x40000
HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_CAT = os.path.normpath(os.path.join(
    HERE, "..", "..", "..", "phase37", "sr-message-catalog.md"))

TABLES = [
    ("g2", 2, 0x10CC18, 0x13),
    ("g0", 0, 0x10CCFC, 0x28),
    ("g0-early", 0, 0x10CBEC, 0x01),
]

def u16(fw, o): return struct.unpack_from("<H", fw, o)[0]
def u32(fw, o): return struct.unpack_from("<I", fw, o)[0]

def fw_tables(fw):
    out = {}
    for label, group, tca, count in TABLES:
        f = tca - BASE
        t = {}
        for i in range(count):
            o = f + i * 12
            idv = u16(fw, o)
            fn = u32(fw, o + 4)
            t[idv] = fn or None
        out[label] = t
    return out

def parse_vendor_catalog(path):
    md = open(path, encoding="utf-8").read()
    sec = md.split("## 2. Catalog")[1].split("## 3.")[0]
    rows = []
    for line in sec.splitlines():
        if not line.startswith("|"):
            continue
        cols = [c.strip() for c in line.strip("|").split("|")]
        if len(cols) < 7:
            continue
        fn, mod, boff, typ, idv, pb, tb = cols[:7]
        if typ in ("clone", "helper", "retry") or cols[0].startswith("posting"):
            continue
        g = None
        if typ not in ("runtime",):
            m = re.match(r"#?([0-9a-fA-Fx]+)$", typ)
            if m:
                g = int(typ.lstrip("#"), 16)
        idn = None
        m = re.match(r"#?([0-9a-fA-Fx]+)$", idv)
        if m:
            idn = int(idv.lstrip("#"), 16)
        if g is None or idn is None:
            continue
        rows.append(dict(fn=fn.strip("`"), mod=mod, builder=boff,
                         group=g, id=idn, payload=pb, total=tb))
    return rows

def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if not args:
        print(__doc__)
        return 2
    fw = open(args[0], "rb").read()
    cat_path = args[1] if len(args) > 1 else DEFAULT_CAT
    vendor = parse_vendor_catalog(cat_path)
    t = fw_tables(fw)
    print("NOTE: generated by tools/h2d_join_vendor.py; do not hand-edit.")
    print()
    print("vendor senders parsed: %d (explicit group/id only)" % len(vendor))
    print()
    print("| grp | id | vendor sender | payload/total B | firmware handler CA/file | note |")
    print("| --- | --- | --- | --- | --- | --- |")
    stats = {}
    for r in sorted(vendor, key=lambda x: (x["group"], x["id"])):
        g = r["group"]
        fn = t["g2"].get(r["id"]) if g == 2 else (t["g0"].get(r["id"]) or t["g0-early"].get(r["id"]))
        note = "handler in table of its own group"
        if g == 2 and fn is None:
            alt = t["g0"].get(r["id"]) or t["g0-early"].get(r["id"])
            if alt:
                fn = alt
                note = "WARNING: handler in the g0 table, not g2"
            else:
                note = "NO handler registered"
        if g == 0 and fn is None:
            note = "NO handler registered"
        key = (g, "hit" if fn else "miss")
        stats[key] = stats.get(key, 0) + 1
        h = ("%#010x / %#07x" % (fn, fn - BASE)) if fn else "-"
        print("| %d | %#04x | %s | %s/%s | %s | %s |" % (g, r["id"], r["fn"], r["payload"], r["total"], h, note))
    print()
    for g in (0, 1, 2):
        hit = stats.get((g, "hit"), 0)
        miss = stats.get((g, "miss"), 0)
        if hit or miss:
            print("- vendor group %d: %d matched / %d explicit senders" % (g, hit, hit + miss))
    if "--all" in sys.argv:
        print()
        print("## firmware table entries with no explicit vendor sender")
        for label, group, tca, count in TABLES:
            ids = set(t[label])
            vids = {r["id"] for r in vendor if r["group"] == group}
            extra = sorted(ids - vids)
            print("- %s (group %d): ids %s" % (label, group, [hex(x) for x in extra]))
    return 0

if __name__ == "__main__":
    sys.exit(main())

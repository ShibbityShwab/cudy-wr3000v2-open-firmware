"""
gen_cfg80211_symvers.py - validate/regenerate the cfg80211 provider symvers
file used by the wifi-cfg80211 lane (task-104) for modpost when the project
6.18.60 tree builds with CONFIG_CFG80211 unset.

The luofu tree ships cfg80211 as the OpenWrt kmod-cfg80211 package, so the
kernel tree's Module.symvers has no cfg80211 exports; out-of-tree modules
that import them declare the provider symbols in a KBUILD_EXTRA_SYMBOLS file
(same technique as ../wifi-wal-glue/glue/cfg80211-provider.symvers).

This tool derives the required symbol set from the actual built objects:
  - undefined symbols of src/hi5622_wifi.o (or every src/*.o)
  - minus everything already provided by the kernel tree Module.symvers
  - intersected with the real EXPORT_SYMBOL/EXPORT_SYMBOL_GPL list parsed
    from <KDIR>/net/wireless/*.c
and then checks (or rewrites) src/cfg80211-provider.symvers.

Exit 0 = provider file is complete and every entry is a real cfg80211 export.
"""
import glob
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_SRC = os.path.join(HERE, "..", "src")
DEFAULT_KDIR = ("/home/shibbityshwab/openwrt-lab-selectorfix-img/build_dir/"
                "target-arm_cortex-a9_musl_eabi/linux-hisilicon_luofu/"
                "linux-6.18.60")
PROVIDER_NAME = "cfg80211-provider.symvers"
EXPORT_RE = re.compile(r"EXPORT_SYMBOL(?:_GPL)?\s*\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*\)")


def tree_symbols(kdir):
    path = os.path.join(kdir, "Module.symvers")
    syms = set()
    if not os.path.isfile(path):
        print("WARNING: %s missing - cannot classify tree-provided symbols" % path)
        return syms
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            parts = line.split()
            if len(parts) >= 2:
                syms.add(parts[1])
    return syms


def wireless_exports(kdir):
    exports = {}
    pattern = os.path.join(kdir, "net", "wireless", "*.c")
    files = glob.glob(pattern)
    if not files:
        print("ERROR: no net/wireless/*.c under %s" % kdir)
        return exports
    for path in files:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            text = fh.read()
        for sym in EXPORT_RE.findall(text):
            exports[sym] = os.path.basename(path)
    return exports


def object_files(src):
    main = os.path.join(src, "hi5622_wifi.o")
    if os.path.isfile(main):
        return [main]
    objs = sorted(p for p in glob.glob(os.path.join(src, "*.o"))
                  if not p.endswith(".mod.o"))
    return objs


def nm_tool():
    cross = os.environ.get("CROSS_COMPILE")
    if cross:
        return cross + "nm"
    return "nm"


def undefined_symbols(objs):
    undef = set()
    nm = nm_tool()
    for obj in objs:
        try:
            out = subprocess.run([nm, "-u", obj], capture_output=True,
                                 text=True, check=False)
        except OSError as exc:
            print("WARNING: cannot run %s: %s" % (nm, exc))
            return undef
        for line in out.stdout.splitlines():
            fields = line.split()
            if len(fields) == 2 and fields[0] == "U":
                undef.add(fields[1])
    return undef


def read_provider(path):
    entries = {}
    if not os.path.isfile(path):
        return entries
    with open(path, "r", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            if len(parts) < 4:
                continue
            entries[parts[1]] = parts[3]
    return entries


def write_provider(path, required, exports):
    lines = ["# cfg80211 provider symbols for modpost - generated by "
             "tools/gen_cfg80211_symvers.py",
             "# The luofu 6.18.60 tree builds CONFIG_CFG80211 unset; the target "
             "kernel sets CONFIG_CFG80211=m",
             "# (see ../cfg80211.config). Every symbol below is a real "
             "EXPORT_SYMBOL/_GPL in <KDIR>/net/wireless/*.c."]
    for sym in sorted(required):
        lines.append("0x00000000\t%s\tcfg80211\t%s\t" %
                     (sym, exports.get(sym, "EXPORT_SYMBOL")))
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


def main(argv):
    update = "--update" in argv
    check = "--check" in argv
    src = DEFAULT_SRC
    kdir = os.environ.get("KDIR", DEFAULT_KDIR)
    i = 1
    while i < len(argv):
        if argv[i] == "--src" and i + 1 < len(argv):
            src = argv[i + 1]
            i += 2
        elif argv[i] == "--kdir" and i + 1 < len(argv):
            kdir = argv[i + 1]
            i += 2
        else:
            i += 1
    src = os.path.abspath(src)
    provider = os.path.join(src, PROVIDER_NAME)
    exports = wireless_exports(kdir)
    tree = tree_symbols(kdir)
    objs = object_files(src)
    if not objs:
        print("WARNING: no built objects under %s - validating entries only" % src)
        undef = set()
    else:
        undef = undefined_symbols(objs)
    external = undef - tree
    required = {s for s in external if s in exports}
    unknown = sorted(s for s in external if s not in exports
                     and re.match(r"^(wiphy_|cfg80211_|ieee80211_)", s))
    entries = read_provider(provider)
    errors = 0

    if unknown:
        print("WARNING: undefined wiphy/cfg80211-family symbols that are NOT "
              "exported from net/wireless/*.c (check API/version):")
        for sym in unknown:
            print("  - %s" % sym)
        errors += 0

    for sym in sorted(entries):
        if sym not in exports:
            print("ERROR: provider symbol %s is not a net/wireless export" % sym)
            errors += 1
        if sym in tree:
            print("ERROR: provider symbol %s is already in the tree Module.symvers" % sym)
            errors += 1
    if objs:
        missing = sorted(required - set(entries))
        extra = sorted(set(entries) - required)
        for sym in missing:
            print("ERROR: required cfg80211 symbol missing from provider file: %s" % sym)
            errors += 1
        for sym in extra:
            print("WARNING: provider symbol no longer imported: %s" % sym)
    if update:
        write_provider(provider, required or set(entries), exports)
        print("UPDATED %s (%d symbols)" % (provider, len(required or entries)))
        return 0
    if errors:
        print("FAIL: %d provider-symbol error(s); run with --update to regenerate"
              % errors)
        return 1
    if check:
        print("OK: %s complete (%d symbols), all real net/wireless exports, "
              "none tree-provided" % (provider, len(entries)))
    else:
        print("OK: %d provider symbols validated" % len(entries))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

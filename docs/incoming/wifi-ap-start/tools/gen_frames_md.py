"""gen_frames_md.py - regenerate ../recipes/frames.md from the selftest emitter.

Lane wifi-ap-start (task-121).  The vectors are SYNTHETIC (built from the
derived field tables), never copied from a vendor artifact.

    python3 tools/gen_frames_md.py --write
    python3 tools/gen_frames_md.py --check
"""
import argparse
import os
import subprocess
import sys

LANE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BIN = os.environ.get("HAF_SELFTEST_BIN", "/tmp/wifi-ap-start-build/ap_frames_selftest")
OUT = os.path.join(LANE, "recipes", "frames.md")
TICK = chr(96) * 3

HEADER = (
    "# wifi-ap-start bench frames (SYNTHETIC)\n\n"
    "Generated by tools/gen_frames_md.py from the host selftest emitter; do not\n"
    "edit by hand.  Every vector is synthesized from the field tables in\n"
    "../REPORT.md / ../TABLES.md - it is NOT a vendor capture and contains no\n"
    "vendor byte.  Byte order in the hex dumps is wire order.  Reproduce with:\n\n"
    + TICK + "\n./tools/build.sh && /tmp/wifi-ap-start-build/ap_frames_selftest --emit\n"
    + TICK + "\n"
)


def emit():
    if not os.path.isfile(BIN):
        sys.stderr.write("error: selftest binary missing: %s (run tools/build.sh)\n" % BIN)
        raise SystemExit(2)
    return subprocess.run([BIN, "--emit"], check=True,
                          stdout=subprocess.PIPE).stdout.decode()


def render():
    text = emit()
    out = [HEADER]
    in_hex = False
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("# "):
            continue
        if line.startswith("## "):
            out.append("\n## %s\n" % line[3:])
            continue
        if line.startswith("### "):
            out.append("\n### %s\n" % line[4:])
            out.append(TICK)
            in_hex = True
            continue
        if not line:
            continue
        out.append(line)
        if in_hex and set(line) <= set("0123456789abcdef "):
            out.append(TICK)
            in_hex = False
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    body = render()
    if args.check:
        if not os.path.isfile(OUT):
            sys.stderr.write("gen_frames_md: %s missing\n" % OUT)
            return 1
        with open(OUT, "r", encoding="utf-8") as fh:
            cur = fh.read()
        if cur != body:
            sys.stderr.write("gen_frames_md: %s is stale (re-run --write)\n" % OUT)
            return 1
        print("gen_frames_md: current")
        return 0
    if args.write:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w", encoding="utf-8") as fh:
            fh.write(body)
        print("gen_frames_md: wrote %s (%u bytes)" % (OUT, len(body)))
        return 0
    ap.print_help()
    return 0


if __name__ == "__main__":
    sys.exit(main())

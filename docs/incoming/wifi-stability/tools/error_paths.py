"""error_paths.py - error-path ladder index, dry-run audit and script emitter.

Lane: wifi-stability (shared task task-136), HOST-ONLY by construction.  It
loads ladders/error-paths.json, statically audits every generated device
action against the project hard rules (the soak.py audit), and can emit the
operator script for an attended fire.  It never contacts the device.

Ladders
  E1  module rmmod/insmod cycling WITHOUT a release (pre-release only)
  E2  AP -> hostapd stop -> driver controlled stop_ap (g0 id9) -> restart
  E3  failed start (clean failure) -> retry with the correct config
  E4  repeated C2 ladder across reboots (idempotency, one cycle per run)
  E5  exception recovery check (mask != 0 -> power-cycle policy)

Usage
  python3 tools/error_paths.py --list
  python3 tools/error_paths.py --dry-run
  python3 tools/error_paths.py --dry-run --ladder E2
  python3 tools/error_paths.py --emit-script E2 > /tmp/e2.sh
"""
from __future__ import annotations

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import soak  # noqa: E402

LADDERS = os.path.join(HERE, "..", "ladders", "error-paths.json")
FORBIDDEN_NO_RMMOD = [x for x in soak.FORBIDDEN if "rmmod" not in x[0]]


def load():
    with open(os.path.abspath(LADDERS)) as f:
        return json.load(f)


def audit_ladder(ladder, text):
    """Audit a generated ladder script; E1 may rmmod only before a release."""
    if ladder.get("allow_rmmod_before_release"):
        bad = []
        for pat, why in FORBIDDEN_NO_RMMOD:
            import re
            if re.search(pat, text):
                bad.append(why)
        # E1 legality is "no release was ever written in this boot"
        if "> \"$D/release\"" in text or "> $D/release" in text:
            bad.append("E1 must never write the release word before rmmod")
        return sorted(set(bad))
    return soak.audit_script(text)


def check_exception_script():
    return """#!/bin/sh
# error_paths E5 - READ-ONLY exception-recovery check (no writes)
set -u
D=/sys/bus/pci/devices/0000:00:00.0
H=/root/hi5622-bar0read
say() { echo "EXC $*"; }
say "uptime=$(cut -d. -f1 /proc/uptime)"
if [ ! -d "$D" ]; then say "NO-ENDPOINT (driver not bound)"; exit 2; fi
if [ ! -x "$H" ]; then say "NO-HELPER $H"; exit 2; fi
RPHYS=$(awk 'NR==1{print $1}' "$D/resource" 2>/dev/null)
BAR0=0
case "$RPHYS" in
0x*|0X*) RH=$RPHYS; RH=$(echo "$RH" | sed -e 's/^0[xX]//'); BAR0=$((0x$RH)) ;;
esac
[ "$BAR0" -gt 0 ] || { say "NO-BAR0 $RPHYS"; exit 2; }
rd() { "$H" $((BAR0 + 0x$1)) 2>/dev/null | head -1; }
P0=$(rd 877000); P1=$(rd 877004); P2=$(rd 877008); P3=$(rd 87700c)
ST=$(rd 7d0b60); MK=$(rd 6f8008); SG=$(rd 6f800c)
say "READBACK page=$P0/$P1/$P2/$P3 state=$ST mask=$MK staging=$SG"
case "$P0 $P1 $P2 $P3 $ST $MK $SG" in
"0x86807fef 0x00000007 0x00000002 0x0000abcd 0x00000001 0x00000000 0x00000000")
	say "CLEAN - golden page/state, mask 0, staging 0"; exit 0 ;;
esac
say "EXCEPTION-DETECTED - power-cycle now (physical RESET/TFTP recovery door"
say "  armed): never unload the driver, never retry H2D, never reuse this boot; capture"
say "  dmesg + the readback above and analyse offline."
exit 3
"""


def emit_script(ladder):
    parts = ["#!/bin/sh",
             "# generated by wifi-stability/tools/error_paths.py - ladder " + ladder["id"],
             "# purpose: " + ladder["purpose"],
             "# ATTENDED, one fresh golden boot, recovery door armed, UART read-only.",
             "set -u",
             "D=/sys/bus/pci/devices/0000:00:00.0",
             "LOG=/tmp/wifi-error-paths",
             "mkdir -p \"$LOG\"",
             "say() { echo \"EP $*\"; }",
             "stop() { echo \"EP-STOP $*\"; exit 1; }",
             ""]
    if ladder.get("bringup"):
        parts.append("# --- evidence bring-up (single boot; the soak helper bring-up) ---")
        parts.append(soak.build_bringup_script(
            {"duration": 600, "interval": 10, "ssid": soak.DEFAULT_SSID,
             "endpoint": soak.ENDPOINT}).replace("SOAK ", "EP ").replace("BRINGUP OK",
                                                                       "BRINGUP PART OK"))
        parts.append("")
    for st in ladder["steps"]:
        parts.append("# step " + st["n"] + ": " + st["action"])
        parts.append("#   expect: " + st["expect"])
        parts.append("say \"STEP " + st["n"] + " start\"")
        for cmd in st.get("sh", []):
            parts.append(cmd)
        if st.get("expect"):
            parts.append("say \"STEP " + st["n"] + " done (compare dmesg/readback to expect)\"")
        parts.append("")
    parts.append("say \"LADDER " + ladder["id"] + " COMPLETE - capture dmesg + readback\"")
    return "\n".join(parts) + "\n"


def cmd_list():
    data = load()
    for lad in data["ladders"]:
        print("%-3s %-58s %s" % (lad["id"], lad["title"],
                                 "bringup" if lad.get("bringup") else "no-bringup"))
    return 0


def cmd_dry_run(ladder_id):
    data = load()
    rc = 0
    for lad in data["ladders"]:
        if ladder_id and lad["id"] != ladder_id:
            continue
        text = emit_script(lad)
        bad = audit_ladder(lad, text)
        print("== %s: %s" % (lad["id"], lad["title"]))
        print("   steps: %d, script lines: %d" % (len(lad["steps"]), text.count(chr(10))))
        print("   classify: " + lad.get("classify", "-"))
        if bad:
            rc = 1
            for b in bad:
                print("   AUDIT-FAIL: " + b)
        else:
            print("   AUDIT OK")
        print("   emit with: --emit-script " + lad["id"])
    if not ladder_id:
        print("DRY-RUN OK" if rc == 0 else "DRY-RUN FAIL")
    return rc


def cmd_selftest():
    data = load()
    checks = 0
    fails = 0

    def chk(name, cond, detail=""):
        nonlocal checks, fails
        checks += 1
        if not cond:
            fails += 1
            print("FAIL %s %s" % (name, detail))

    ids = [lad["id"] for lad in data["ladders"]]
    chk("ladder-ids", ids == ["E1", "E2", "E3", "E4", "E5"], str(ids))
    for lad in data["ladders"]:
        text = emit_script(lad)
        bad = audit_ladder(lad, text)
        chk("audit-%s" % lad["id"], not bad, str(bad))
        chk("steps-%s" % lad["id"], len(lad["steps"]) >= (2 if lad["id"] == "E5" else 3))
        for st in lad["steps"]:
            chk("%s-%s-expect" % (lad["id"], st["n"]), bool(st.get("expect")))
    exc = check_exception_script()
    chk("e5-read-only", soak.audit_script(exc) == [], str(soak.audit_script(exc)))
    chk("e5-recovery-policy", "power-cycle" in exc)
    # the E1 special path must reject a stray release write
    bad = audit_ladder({"allow_rmmod_before_release": True},
                       "echo 1 > \"$D/release\"\nrmmod hi5622_wifi\n")
    chk("e1-rejects-release", any("release" in b for b in bad), str(bad))
    print("error_paths_selftest: %d passed, %d failed" % (checks - fails, fails))
    return 0 if fails == 0 else 1


def main(argv=None):
    ap = argparse.ArgumentParser(description="error-path ladder index/audit")
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--ladder", default="")
    ap.add_argument("--emit-script", default="")
    a = ap.parse_args(argv)
    if a.list:
        return cmd_list()
    if a.selftest:
        return cmd_selftest()
    if a.emit_script:
        for lad in load()["ladders"]:
            if lad["id"] == a.emit_script:
                sys.stdout.write(emit_script(lad))
                return 0
        raise SystemExit("error_paths: unknown ladder " + a.emit_script)
    return cmd_dry_run(a.ladder)


if __name__ == "__main__":
    sys.exit(main())

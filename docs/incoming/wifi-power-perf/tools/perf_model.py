"""perf_model.py - independent host model of the Hi5622 clean-room TX, scan,
poll and beacon/DTIM limits (wifi-power-perf lane, task-160).

The point of a SECOND implementation (the first is src/hi5622_pm_perf_logic.h,
used by the kernel module and pm_perf_selftest.c) is that the numbers quoted in
the report are checked by code that does not share the driver's arithmetic.

Inputs are the constants pinned in the report with their evidence grade:
  - ring geometry / pool / MPDU bound / poll: driver sources and dp_rings.h
  - scan pace / 6-channel firmware cap: measured baseline (wifi-perf-baseline)
  - beacon 100 TU / DTIM 2: measured hostapd AP facts
  - frame timing (preamble/SIFS/ACK/DIFS/backoff): classic 802.11 values [I]

Usage: perf_model.py [--check] [--write PATH]
"""
import sys

# ---- pinned inputs ---------------------------------------------------------
TX_RING_DEPTH = 64        # [V] per-TID MSDU ring
TX_RING_COUNT = 8         # [V]
TX_POOL_DEPTH = 16        # [V*] host in-flight pool (shipped)
TX_MPDU_MAX = 768         # [V] DP_TXRX_MAX_MPDU
TX_POLL_MS = 5            # [V*] completion rearm
HDR = 24 + 8              # 802.11 data hdr + LLC/SNAP

SCAN_PER_CH_MS = 156      # [V*]
SCAN_FW_MAX_CH = 6        # [V*]
SCAN_BATCH_GAP_MS = 300   # driver default
SCAN_CHANNELS_24 = 13     # full 2.4 GHz list (1..13)

BEACON_TU = 100           # [V*]
DTIM = 2                  # [V*]

# classic 802.11 timing for a non-aggregated HT-mixed 20 MHz 1SS frame [I]
PREAMBLE_US = 40
SIFS_US = 10
ACK_US = 40
DIFS_US = 34
BACKOFF_SLOTS = 8
SLOT_US = 9
OVERHEAD_US = SIFS_US + ACK_US + DIFS_US + BACKOFF_SLOTS * SLOT_US


def tx_pps(pool, poll_ms):
    return 0 if poll_ms <= 0 or pool <= 0 else (pool * 1000) // poll_ms


def frame_cycle_us(mpdu_bytes, phy_kbps):
    """Return (frame_us, cycle_us, pps, payload_bps) for one frame."""
    if phy_kbps <= 0:
        raise ValueError("phy_kbps must be > 0")
    bits = mpdu_bytes * 8
    data_us = -(-bits * 1000 // phy_kbps)      # ceil
    frame_us = PREAMBLE_US + data_us
    cycle_us = frame_us + OVERHEAD_US
    pps = 1_000_000 // cycle_us
    payload = max(0, mpdu_bytes - HDR) * 8 * pps
    return frame_us, cycle_us, pps, payload


def scan_requests(channels, batch):
    if channels <= 0 or batch <= 0 or batch >= channels:
        return 1
    return (channels + batch - 1) // batch


def scan_total_ms(channels, per_ch_ms):
    return channels * per_ch_ms


def scan_batched_ms(channels, batch, per_ch_ms, gap_ms):
    reqs = scan_requests(channels, batch)
    return scan_total_ms(channels, per_ch_ms) + (reqs - 1) * gap_ms


def beacon_ms(tu):
    return max(1, (tu * 1024) // 1000)


def client_wakeups_per_min(tu, dtim):
    return 60000 // (beacon_ms(tu) * dtim)


def render():
    out = []
    w = out.append
    w("# Derived performance model (wifi-power-perf, task-160)")
    w("")
    w("Generated by tools/perf_model.py; every number is a **model**, not a")
    w("bench measurement. Grades: geometry [V], shipped values [V*], frame")
    w("timing [I]. The attended ladders in LADDER-BENCH.md are what promote a")
    w("row from model to [V*].")
    w("")
    w("## 1. Host TX window (in-flight pool x completion poll)")
    w("")
    w("The data-TX lane keeps at most HDTX_POOL_DEPTH frames in flight and")
    w("frees completions only when the delayed work runs (data_tx_poll_ms,")
    w("default 5): the host ceiling is pool x (1000 / poll_ms) frames/s of")
    w("MPDU bytes. MPDU <= 768 B, one TID, non-QoS, no aggregation.")
    w("")
    w("| pool | poll_ms | frames/s | MPDU MB/s | payload Mbps (736 B app) |")
    w("| ---: | ---: | ---: | ---: | ---: |")
    for pool in (16, 32, 64):
        for poll in (5, 2, 1):
            pps = tx_pps(pool, poll)
            mb = pps * TX_MPDU_MAX / 1e6
            pbps = pps * (TX_MPDU_MAX - HDR) * 8 / 1e6
            w(f"| {pool} | {poll} | {pps} | {mb:.2f} | {pbps:.1f} |")
    w("")
    w("Shipped default: pool 16 at 5 ms = **3200 frames/s = 2.46 MB/s MPDU =")
    w("18.8 Mbps of 736 B payload**.")
    w("")
    w("## 2. Single-frame air ceiling (no aggregation)")
    w("")
    w(f"HT-mixed 20 MHz 1SS frame timing model: preamble {PREAMBLE_US} us,")
    w(f"data = ceil(MPDU*8/PHY), SIFS+ACK+DIFS+avg-backoff = {OVERHEAD_US} us.")
    w("")
    w("| MPDU B | PHY | frame us | cycle us | frames/s | payload Mbps |")
    w("| ---: | ---: | ---: | ---: | ---: | ---: |")
    for phy, name in ((65000, "65 Mbps MCS7/20MHz/1SS"),
                      (130000, "130 Mbps MCS15/20MHz/2SS"),
                      (288200, "288 Mbps MCS9/HT40/2SS [I]")):
        for size in (TX_MPDU_MAX, 1500):
            fu, cu, pps, pb = frame_cycle_us(size, phy)
            w(f"| {size} | {name} | {fu} | {cu} | {pps} | {pb/1e6:.1f} |")
    w("")
    w("Consequence: at 2.4 GHz MCS7 the non-aggregated air ceiling is ~3.4k")
    w("frames/s, i.e. the shipped host window (3.2k) is already within 6 % of")
    w("the air ceiling - the stack is **air-bound, not poll-bound**, at the")
    w("default 2.4 GHz rate. A faster PHY moves the bind to the host window:")
    w("raising the pool to the 64-entry ring depth makes the host window")
    w("12.8k frames/s at 5 ms. Aggregation (A-MPDU) is the only step that")
    w("removes the per-frame overhead, and it is not implemented in this")
    w("clean-room stack (firmware/BA session support unproven).")
    w("")
    w("## 3. Scan pace (measured + batched model)")
    w("")
    w(f"Measured: {SCAN_PER_CH_MS} ms/channel, firmware stops after")
    w(f"{SCAN_FW_MAX_CH} channels per g0 id0xC request. Driver batches")
    w(f"ceil(n/batch) requests with a {SCAN_BATCH_GAP_MS} ms gap.")
    w("")
    w("| channels | batch | requests | model wall time ms |")
    w("| ---: | ---: | ---: | ---: |")
    for ch, batch in ((6, 6), (13, 0), (13, 6), (13, 7), (13, 8)):
        w(f"| {ch} | {batch or 'single'} | {scan_requests(ch, batch)} | "
          f"{scan_batched_ms(ch, batch, SCAN_PER_CH_MS, SCAN_BATCH_GAP_MS)} |")
    w("")
    w("A full 13-channel scan is structurally blocked at the DMAC (per the")
    w("sibling analysis): the 7/8-channel band-config rung (H1) is the")
    w("documented ceiling, so the batch=6 default plus gap is the correct")
    w("production shape; 13 channels are covered as 3 requests only if the")
    w("firmware re-arms its scan context (unproven).")
    w("")
    w("## 4. Beacon / DTIM (client power, not AP power)")
    w(f"Beacon {BEACON_TU} TU = {beacon_ms(BEACON_TU)} ms; the AP chip is")
    w("always-on in our stack, so DTIM changes client wakeups only.")
    w("")
    w("| beacon TU | DTIM | client wakeups/min |")
    w("| ---: | ---: | ---: |")
    for tu in (100, 200):
        for dtim in (1, 2, 3, 5, 10):
            w(f"| {tu} | {dtim} | {client_wakeups_per_min(tu, dtim)} |")
    w("")
    w("## 5. Service-poll wakeup cost")
    w("")
    w("| cadence ms | wakeups/s/endpoint | wakeups/s for 2 endpoints |")
    w("| ---: | ---: | ---: |")
    for ms in (1, 5, 20, 50):
        w(f"| {ms} | {1000 // ms} | {2 * (1000 // ms)} |")
    w("")
    w("5 ms -> 200/s/endpoint (measured ~145 effective/s in the live sample);")
    w("idle backoff to 20 ms cuts that 4x with no traffic to delay.")
    w("")
    return "\n".join(out) + "\n"


def check():
    ok = True
    def expect(cond, what):
        nonlocal ok
        if not cond:
            ok = False
            print(f"FAIL: {what}")
    expect(tx_pps(16, 5) == 3200, "shipped host window 3200 fps")
    expect(tx_pps(64, 5) == 12800, "ring-depth host window 12800 fps")
    expect(tx_pps(16, 0) == 0, "zero poll interval refused")
    fu, cu, pps, pb = frame_cycle_us(768, 65000)
    expect((fu, cu, pps) == (135, 291, 3436), "768 B MCS7 frame model")
    expect(pb == 3436 * 736 * 8, "payload bps formula")
    expect(scan_total_ms(13, 156) == 2028, "13-channel scan time")
    expect(scan_requests(13, 6) == 3, "batch=6 -> 3 requests")
    expect(scan_batched_ms(13, 6, 156, 300) == 2028 + 600, "batched scan time")
    expect(scan_requests(13, 0) == 1, "legacy single request")
    expect(beacon_ms(100) == 102, "beacon 100 TU")
    expect(client_wakeups_per_min(100, 2) == 294, "DTIM 2 wakeups")
    expect(client_wakeups_per_min(100, 1) == 588, "DTIM 1 wakeups")
    # the shipped window must not exceed the 2.4 GHz MCS7 air ceiling
    expect(tx_pps(16, 5) <= pps, "air-bound at MCS7")
    return ok


def main(argv):
    write = None
    if "--write" in argv:
        write = argv[argv.index("--write") + 1]
    ok = check()
    text = render()
    if write:
        with open(write, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"perf_model: wrote {write} ({len(text)} bytes)")
    if "--check" in argv or not write:
        print(text)
    print(f"perf_model: checks {'PASS' if ok else 'FAIL'}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

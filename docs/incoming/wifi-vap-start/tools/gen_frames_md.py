"""gen_frames_md.py - regenerate recipes/frames.md from the selftest emitter.

Host-only; runs the strict selftest binary and the emit mode, then formats the
byte-exact bench frames.  Usage: tools/gen_frames_md.py [--check]
"""
import argparse
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LANE = os.path.dirname(HERE)
BUILD = os.environ.get("OUT", "/tmp/wifi-vap-start-build")
BIN = os.path.join(BUILD, "vapstart_selftest")
OUT = os.path.join(LANE, "recipes", "frames.md")

FRAMES = [
    ("vap_add_g0id1_key0x64", "g0 id1 key 0x0064 VAP add (module context create)",
     "48", "consumed, no exception mask, no staging frame"),
    ("vap_start_g0id1_key0x65", "g0 id1 key 0x0065 VAP start",
     "40", "consumed, no exception mask"),
    ("sta_join_start_g0id0x10", "g0 id 0x0010 start_sta/join start",
     "28", "consumed; only with a real join context"),
    ("sta_join_params_g0id0x0F", "g0 id 0x000F join-request params",
     "76", "consumed; only with a real join context"),
    ("wal_vap_add_g2_cmd0x64", "WAL group-2 cfg event cmd 0x0064 VAP add (vendor order)",
     "56", "consumed; firmware VAP layer create"),
    ("wal_vap_start_g2_cmd0x65", "WAL group-2 cfg event cmd 0x0065 VAP start (vendor order)",
     "44", "consumed; firmware VAP layer start"),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="fail if recipes/frames.md is stale")
    args = ap.parse_args()

    subprocess.run([os.path.join(HERE, "build.sh")], check=True,
                   stdout=subprocess.DEVNULL)
    raw = subprocess.run([BIN, "--emit-raw"], check=True,
                         capture_output=True, text=True).stdout
    frames = {}
    for line in raw.splitlines():
        if "total=" not in line:
            continue
        name, rest = line.split(" total=", 1)
        total, hexs = rest.split(": ", 1)
        frames[name.strip()] = (total.strip(), hexs.strip())

    lines = []
    lines.append("# Byte-exact bench frames - wifi-vap-start lane (generated)")
    lines.append("")
    lines.append("Generated by `tools/gen_frames_md.py` from `src/vapstart_selftest.c`")
    lines.append("(`--emit-raw`); do not edit by hand.  The KATs in the selftest are the")
    lines.append("source of truth.  Every frame below is SYNTHESIZED from the decoded")
    lines.append("firmware parser and vendor builder behaviour (REPORT.md sections 4-7) -")
    lines.append("none is a vendor capture.")
    lines.append("")
    lines.append("Carrier: one ETE SR node {devva, (total<<16)|0x6d2b}, then the packed")
    lines.append("producer update, then the coalesced mailbox id-3 announce - the same")
    lines.append("carrier every post-ready H2D lane uses.")
    lines.append("")
    lines.append("| name | family | total | expected immediate observable |")
    lines.append("| --- | --- | ---: | --- |")
    for name, family, total, expect in FRAMES:
        lines.append("| `%s` | %s | %s | %s |" % (name, family, total, expect))
    lines.append("")
    lines.append("## Wire bytes (hex)")
    lines.append("")
    for name, family, total, expect in FRAMES:
        total_got, hexs = frames[name]
        if total_got != total:
            raise SystemExit("total drift for %s: %s != %s" % (name, total_got, total))
        lines.append("### %s - %s - %s B" % (name, family, total))
        lines.append("")
        lines.append("```")
        lines.append(hexs)
        lines.append("```")
        lines.append("")
    text = "\n".join(lines) + "\n"

    if args.check:
        old = open(OUT).read() if os.path.exists(OUT) else ""
        if old != text:
            print("recipes/frames.md is stale - run tools/gen_frames_md.py")
            return 1
        print("recipes/frames.md is current")
        return 0

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write(text)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
